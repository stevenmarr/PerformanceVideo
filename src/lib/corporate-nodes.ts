/**
 * Starter models for live corporate video.
 * Connections are the ones a patch list uses. A card frame is a typical rental load,
 * not every optional slot. A lower SDI rate can land on a faster SDI connection.
 * HDMI, DisplayPort, DVI, fiber, and LED families do not cross.
 */
export type GearPin = [string, "input" | "output", string];

export type GearSeed = {
  type: string;
  maker: string;
  model: string;
  kind: string;
  notes: string;
  pins: GearPin[];
  pack?: number;
};

function jacks(prefix: string, count: number, direction: GearPin[1], signal: string): GearPin[] {
  return Array.from({ length: count }, (_, index) => [`${prefix} ${index + 1}`, direction, signal]);
}

